export type MessageKey = keyof typeof messages;
export const dictionaries = {
  en: Object.fromEntries(Object.entries(messages).map(([k, v]) => [k, v[0]])),
  fr: Object.fromEntries(Object.entries(messages).map(([k, v]) => [k, v[1]])),
  ar: Object.fromEntries(Object.entries(messages).map(([k, v]) => [k, v[2]])),
} as Record<Locale, Record<MessageKey, string>>;
const cache = new Map<string, IntlMessageFormat>();
export function translate(locale: Locale, key: MessageKey, values?: Record<string, string | number>): string {
  const cacheKey = `${locale}:${key}`;
  let formatter = cache.get(cacheKey);
  if (!formatter) {
    formatter = new IntlMessageFormat(
      dictionaries[locale][key] ?? dictionaries[locale].INTERNAL_ERROR,
      locale,
    );
    cache.set(cacheKey, formatter);
  }
  return String(formatter.format(values));
}
export function messageKey(value: string): MessageKey | undefined {
  return value in messages ? (value as MessageKey) : undefined;
}
