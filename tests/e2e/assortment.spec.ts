import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { randomUUID } from 'node:crypto';
import { mkdir, readFile } from 'node:fs/promises';
import { login, navigate, switchLanguage } from './helpers';
import { translate as t } from '../../packages/i18n/src/business';

test('Older password-only loopback previews keep the demo notice during an upgrade', async ({page}) => {
  await page.route('**/api/config', route => route.fulfill({json:{defaultLocale:'en',passwordOnlyLogin:true}}));
  await page.goto('/');
  await switchLanguage(page,'en');
  await expect(page.getByText(t('en','demoNotice'),{exact:true})).toBeVisible();
  await expect(page.getByTestId('login-totp')).toHaveCount(0);
});

test('Merchandise directory works before stock exists and carries a trilingual type into registration', async ({page,request}) => {
  await page.setViewportSize({width:390,height:844});
  expect((await request.get('/api/catalog/assortment')).status()).toBe(401);
  await login(page,'owner');
  const result = await (await page.request.get('/api/catalog/assortment?group=TOOLS&q=valise')).json();
  expect(result.items.map((row:{code:string}) => row.code)).toContain('TOOLS_DIAG');
  await switchLanguage(page,'en');
  await navigate(page,'catalog');
  await page.getByRole('button',{name:t('en','browseTypes')}).click();
  const modal = () => page.getByRole('dialog').last();
  await modal().getByLabel(t('en','assortmentGroup')).selectOption('TOOLS');
  await modal().getByRole('searchbox').fill('valise');
  await switchLanguage(page,'ar');
  await expect(modal().getByRole('searchbox')).toHaveValue('valise');
  await expect(modal().getByLabel(t('ar','assortmentGroup'))).toHaveValue('TOOLS');
  const download = page.waitForEvent('download');
  await modal().getByRole('button',{name:t('ar','downloadTypes')}).click();
  const csv = await readFile((await (await download).path())!, 'utf8');
  expect(csv).toContain('"TOOLS_DIAG"');
  expect(csv).not.toContain('"BRAKE_PAD"');
  const axe = await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
  expect(axe.violations.map(v => v.id)).toEqual([]);
  await mkdir('docs/evidence/assortment',{recursive:true});
  await page.screenshot({path:'docs/evidence/assortment/phone-ar.png'});
  await modal().getByRole('button',{name:result.items[0].names.ar,exact:true}).click();
  await page.getByTestId('product-create').click();
  await expect(modal().getByTestId('product-category')).toHaveValue('TOOLS_DIAG');
  const sku = 'ASSORT-'+randomUUID().slice(0,12);
  await modal().getByTestId('product-sku').fill(sku);
  await modal().getByTestId('product-brand').fill('SYNTHETIC');
  await modal().getByTestId('product-name-en').fill('Workshop test item');
  await switchLanguage(page,'fr');
  await modal().getByRole('button',{name:t('fr','browseTypes')}).click();
  await modal().getByRole('searchbox').fill('DETAILING_ODOR');
  await modal().getByRole('button',{name:'Désodorisants et neutralisants'}).click();
  await expect(modal().getByTestId('product-sku')).toHaveValue(sku);
  await modal().getByTestId('product-submit').click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const response = await page.request.get('/api/products?q='+sku+'&category=DETAILING_ODOR');
  const item = (await response.json()).items[0];
  expect(item.sku).toBe(sku);
  expect(item.categoryNames.fr).toBe('Désodorisants et neutralisants');
  expect(item.categoryNames.ar).toContain('معطرات');
  expect(item.categoryNames.en).toContain('Air fresheners');
  expect(item.stock).toHaveLength(0);
  expect(item.fitments).toHaveLength(0);
});
