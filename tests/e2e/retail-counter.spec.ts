import {test,expect} from '@playwright/test';
import {randomUUID} from 'node:crypto';
import {mkdir} from 'node:fs/promises';
import {login,navigate,switchLanguage} from './helpers';
import {translate as t} from '../../packages/i18n/src/business';

test('Counter range filters on a phone and stores only the actual oil label entered by the operator',async({page})=>{
  await page.setViewportSize({width:390,height:844});
  await login(page,'owner');
  await switchLanguage(page,'ar');
  await navigate(page,'catalog');
  const official = await (await page.request.get('/api/catalog/assortment?range=counter')).json();
  expect(official.total).toBe(68);
  await page.getByRole('button',{name:t('ar','browseTypes')}).click();
  const modal=()=>page.getByRole('dialog').last();
  await modal().getByLabel(t('ar','counterEssentials')).check();
  await modal().getByRole('searchbox').fill('٥W٣٠');
  await expect(modal().getByRole('button',{name:'زيت المحرك 5W-30'})).toBeVisible();
  await mkdir('docs/evidence/assortment',{recursive:true});
  await page.screenshot({path:'docs/evidence/assortment/aaa-counter-ar.png'});
  await switchLanguage(page,'fr');
  await expect(modal().getByLabel(t('fr','counterEssentials'))).toBeChecked();
  await modal().getByRole('button',{name:'Huile moteur 5W-30'}).click();
  await page.getByTestId('product-create').click();
  const sku='AAA-TEST-'+randomUUID().slice(0,8);
  await modal().getByTestId('product-sku').fill(sku);
  await modal().getByTestId('product-brand').fill('SYNTHETIC');
  await modal().getByTestId('product-name-fr').fill('Bidon de test');
  await modal().getByLabel('Contenance ou poids du conditionnement').fill('5 L');
  await modal().getByLabel('Grade de viscosité').fill('5W-30');
  await switchLanguage(page,'en');
  await expect(modal().getByLabel('Pack capacity or weight')).toHaveValue('5 L');
  await expect(modal().getByLabel('Specification printed on the label')).toHaveValue('');
  await modal().getByTestId('product-submit').click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const product=(await (await page.request.get('/api/products?q='+sku)).json()).items[0];
  expect(product.category).toBe('MOTOR_OILS_5W30');
  expect(product.companyMetadata.technicalAttributes.map((attr:{code:string;value:string})=>[attr.code,attr.value])).toEqual([['retail_pack','5 L'],['retail_sae','5W-30']]);
  expect(product.stock).toHaveLength(0);
  expect(product.fitments).toHaveLength(0);
});
