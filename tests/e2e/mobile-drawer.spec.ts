import {expect, test} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import {currentSession, login, password, switchLanguage} from './helpers';
import {translate} from '../../packages/i18n/src/business';

test('Mobile sales navigation keeps the cart and focus through language changes and keyboard dismissal', async ({page}) => {
  await page.setViewportSize({width:320, height:844});
  await login(page, 'sales');
  const sku = 'AP-SPK-004';
  await page.getByTestId('product-search').fill(sku);
  await page.getByTestId(`add-to-cart-${sku}`).click();
  const quantity = page.getByTestId(`cart-quantity-${sku}`);
  await quantity.fill('2');
  const totalBefore = await page.getByTestId('cart-total').getAttribute('data-minor');
  const trigger = page.locator('.mobile-menu');
  const drawer = page.locator('dialog.mobile-drawer[open]');
  await trigger.press('Enter');
  await expect(drawer.getByTestId('nav-pos')).toBeFocused();
  expect(await drawer.evaluate(el=>el.matches(':modal'))).toBe(true);
  await page.locator('#main').evaluate(el=>el.focus());
  await expect(drawer.getByTestId('nav-pos')).toBeFocused();
  await page.keyboard.press('Control+k');
  await expect(page.locator('dialog[open]')).toHaveCount(1);
  await switchLanguage(page,'ar');
  await expect(drawer.getByTestId('nav-pos')).toHaveAttribute('aria-current','page');
  const findings = await new AxeBuilder({page}).include('dialog[open]')
    .withTags(['wcag2a','wcag2aa','wcag21a','wcag21aa']).analyze();
  expect(findings.violations.map(v=>v.id)).toEqual([]);
  await drawer.getByTestId('language-toggle').click();
  const popup = await drawer.locator('.language-options').boundingBox(), panel = await drawer.boundingBox();
  expect(popup).not.toBeNull();
  expect(popup!.x).toBeGreaterThanOrEqual(panel!.x);
  expect(popup!.x+popup!.width).toBeLessThanOrEqual(panel!.x+panel!.width+1);
  await page.keyboard.press('Escape');
  await expect(drawer.getByTestId('language-picker')).not.toHaveAttribute('open','');
  await expect(drawer.getByTestId('language-toggle')).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(drawer).toHaveCount(0);
  await expect(trigger).toBeFocused();
  await trigger.press('Enter');
  await drawer.getByTestId('nav-catalog').press('Enter');
  await expect(page.locator('main#main')).toBeFocused();
  await expect(page.getByTestId('nav-catalog')).toHaveAttribute('aria-current','page');
  await trigger.click();
  await switchLanguage(page,'fr');
  await drawer.getByTestId('nav-pos').click();
  await expect(page.locator('main#main')).toBeFocused();
  await expect(quantity).toHaveValue('2');
  await expect(page.getByTestId('cart-total')).toHaveAttribute('data-minor',totalBefore!);
  await trigger.click();
  await page.route('**/api/auth/logout', route=>route.abort('failed'), {times:1});
  await drawer.getByTestId('logout').click();
  await expect(drawer.getByRole('alert')).toContainText(translate('fr','NETWORK_ERROR'));
  await page.keyboard.press('Escape');
  await expect(quantity).toHaveValue('2');
  await trigger.click();
  await drawer.getByTestId('logout').click();
  await expect(page.getByTestId('login-email')).toBeVisible();
});

test('Owner drawer transfers to desktop navigation and yields to the session lock', async ({page}) => {
  await page.setViewportSize({width:390,height:844});
  await login(page,'owner');
  await switchLanguage(page,'en');
  const trigger=page.locator('.mobile-menu'), drawer=page.locator('dialog.mobile-drawer[open]');
  await trigger.click();
  await expect(drawer.getByTestId('nav-dashboard')).toBeFocused();
  await expect(drawer.getByTestId('nav-team')).toBeAttached();
  await page.setViewportSize({width:1024,height:768});
  await expect(drawer).toHaveCount(0);
  await expect(page.getByTestId('nav-dashboard')).toBeFocused();
  await page.getByTestId('nav-team').click();
  await expect(page.getByTestId('nav-team')).toHaveAttribute('aria-current','page');
  await page.setViewportSize({width:390,height:844});
  await expect(trigger).toHaveAttribute('aria-expanded','false');
  await trigger.click();
  await page.evaluate(()=>window.dispatchEvent(new Event('autoparts-session-expired')));
  await expect(drawer).toHaveCount(0);
  await expect(page.locator('.lock-overlay')).toBeVisible();
  await expect(trigger).toBeDisabled();
});

test('Session lock covers an open search, preserves its draft and restores focus after reauthentication', async ({page}) => {
  await page.setViewportSize({width:390,height:844});
  await login(page,'sales');
  await switchLanguage(page,'en');
  await page.getByTestId('workspace-search').click();
  const query=page.getByTestId('workspace-query');
  await expect(query).toBeFocused();
  const original=await currentSession(page);
  const expired=await page.request.post('/api/auth/lock',{data:{},headers:{'x-csrf-token':original.csrfToken}});
  expect(expired.ok()).toBe(true);
  const searched=page.waitForResponse(response=>response.url().includes('/api/workspace/search?'));
  await query.fill('AP-FLT-001');
  expect((await searched).status()).toBe(401);
  const lock=page.locator('dialog.lock-overlay[open]');
  await expect(lock).toBeVisible();
  expect(await lock.evaluate(el=>el.matches(':modal') && el.contains(document.elementFromPoint(1,1)))).toBe(true);
  await expect(lock.getByTestId('login-password')).toBeFocused();
  await query.evaluate(el=>el.focus());
  await expect(lock.getByTestId('login-password')).toBeFocused();
  await switchLanguage(page,'ar');
  await expect(lock.getByRole('heading',{name:translate('ar','locked')})).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(lock).toBeVisible();
  expect((await page.request.get('/api/me')).status()).toBe(401);
  await lock.getByTestId('login-password').fill(password());
  await lock.getByTestId('login-submit').click();
  await expect(lock).toHaveCount(0);
  await expect(query).toHaveValue('AP-FLT-001');
  await expect(query).toBeFocused();
  await expect.poll(async()=> (await currentSession(page)).user.locale).toBe('ar');
  await page.getByRole('button',{name:translate('ar','refresh'),exact:true}).click();
  await expect(page.locator('.workspace-results')).toContainText('AP-FLT-001');
});
